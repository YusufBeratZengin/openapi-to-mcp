import { existsSync, readFileSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Manifest } from './runtime.js';
import { validateConfig } from './runtime.js';

interface OwnPackage {
  version: string;
  dependencies: Record<string, string>;
}

export function ownPackage(): OwnPackage {
  const file = fileURLToPath(new URL('../package.json', import.meta.url));
  return JSON.parse(readFileSync(file, 'utf8')) as OwnPackage;
}

/** Locate a compiled runtime file (next to this module, or in ../dist during tests). */
function compiledFile(name: string): string {
  const here = path.dirname(fileURLToPath(import.meta.url));
  for (const candidate of [path.join(here, name), path.join(here, '..', 'dist', name)]) {
    if (existsSync(candidate)) {
      return candidate;
    }
  }
  throw new Error(`Compiled file ${name} not found; run "npm run build" first`);
}

const SERVER_SOURCE = `#!/usr/bin/env node
// Generated by openapi-to-mcp. Edit tools.json or this file freely.
import { readFileSync } from 'node:fs';
import { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js';
import { createMcpServer } from './mcp.js';

const manifest = JSON.parse(readFileSync(new URL('./tools.json', import.meta.url), 'utf8'));

try {
  const server = createMcpServer(manifest, {}, { name: __NAME__, version: '0.1.0' });
  await server.connect(new StdioServerTransport());
  console.error(\`MCP server ready: \${manifest.tools.length} tools\`);
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
}
`;

export interface GenerateOptions {
  /** Name used for the package and MCP server. */
  name?: string;
}

/** Write a standalone MCP server project into `outDir`. */
export async function generateProject(
  manifest: Manifest,
  outDir: string,
  options: GenerateOptions = {},
): Promise<string[]> {
  validateConfig(manifest.config);
  const name = (options.name ?? 'generated-mcp-server').replace(/[^a-z0-9._-]+/gi, '-').replace(/^[._-]+/, '').toLowerCase()
    || 'generated-mcp-server';
  const own = ownPackage();
  await mkdir(outDir, { recursive: true });

  const files: Record<string, string> = {
    'tools.json': `${JSON.stringify(manifest, null, 2)}\n`,
    'server.mjs': SERVER_SOURCE.replace('__NAME__', JSON.stringify(name)),
    'runtime.js': await readFile(compiledFile('runtime.js'), 'utf8'),
    'mcp.js': await readFile(compiledFile('mcp.js'), 'utf8'),
    'package.json': `${JSON.stringify(
      {
        name,
        version: '0.1.0',
        private: true,
        type: 'module',
        bin: { [name]: 'server.mjs' },
        scripts: { start: 'node server.mjs' },
        engines: { node: '>=20' },
        dependencies: {
          '@modelcontextprotocol/sdk': own.dependencies['@modelcontextprotocol/sdk'],
        },
      },
      null,
      2,
    )}\n`,
    'README.md': readme(name, manifest),
  };

  const written: string[] = [];
  for (const file of Object.keys(files)) {
    if (existsSync(path.join(outDir, file))) {
      throw new Error(`Refusing to overwrite existing generated file "${file}"`);
    }
  }
  for (const [file, content] of Object.entries(files)) {
    await writeFile(path.join(outDir, file), content, { encoding: 'utf8', flag: 'wx' });
    written.push(file);
  }
  return written;
}

function readme(name: string, manifest: Manifest): string {
  const { config, tools } = manifest;
  const env = [
    ...(config.bearerEnv ? [config.bearerEnv] : []),
    ...Object.values(config.headerEnv),
  ];
  return `# ${name}

MCP server generated by [openapi-to-mcp](https://github.com/YusufBeratZengin/openapi-to-mcp).

- Base URL: \`${config.baseUrl}\`
- Allowed hosts: ${config.allowedHosts.map((h) => `\`${h}\``).join(', ')}
- Write operations: ${config.allowWrite ? 'enabled' : 'disabled'}
- Tools: ${tools.length}
${env.length > 0 ? `- Required environment variables: ${env.map((e) => `\`${e}\``).join(', ')}\n` : ''}
## Run

\`\`\`sh
npm install
node server.mjs
\`\`\`

Add it to an MCP client as a stdio server with command \`node\` and argument \`server.mjs\`.
Set \`OPENAPI_MCP_BASE_URL\` to point at another host from the allowed list.
`;
}
